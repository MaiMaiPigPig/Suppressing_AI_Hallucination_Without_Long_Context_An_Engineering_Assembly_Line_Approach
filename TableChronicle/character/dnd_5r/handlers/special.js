// ============================================================
// 特殊标记处理器 - 全局作用域
// ============================================================
//
// 【这个文件有什么用？】
// 处理一些特殊的标记性规则。
// 这些规则不直接产生数据操作，而是给特性"打标签"。
//
// 匹配规则：
//   二选一       — 标记该特性为"二选一"（与另一个特性互斥）
//   环位：+[N]   — 标记法术每升一环增加的效果数值
//
// 特点：
//   - 纯标记，不需要用户选择
//   - 实际逻辑由其他代码处理，这里只做识别和标记
//
// 【调用方式】
// 外部通过 index.js 的 parseRule() 自动路由过来：
//   handlers.parseRule("二选一")     → 标记为二选一
//   handlers.parseRule("环位：+1")   → 标记每升一环增加1d6伤害
//
// 【返回值用法】
//   if (result.type === 'special') {
//     if (result.subtype === 'choose_one') {
//       // 这个特性是"二选一"中的一项，需要找另一个同样标记的特性
//       // 用户只能选择其中一个
//     } else if (result.subtype === 'upcast') {
//       // 这个法术有升环效果，每升一环，效果提升 result.value
//       // 比如：环位：+1 → 每升一环多1d8伤害
//     }
//   }
//
// 【JS语法 - 给初学者】
//   function(rule) { rule = String(rule).trim(); ... }
//   String(rule) 把任意类型转成字符串。
//   .trim() 去掉字符串首尾的空格。
//   这两步是"防御性编程"，确保传入的值一定是干净的字符串。
//
//   if (rule === '二选一') { ... }
//   === 是"严格相等"比较，值和类型都必须相等。
//   '二选一' 是字符串字面量，用单引号或双引号都可以。
//   JS 中字符串用 === 比较是直接比较字符内容。
//
//   /^环位：\s*\+\s*(\d+)\s*$/
//   中文字符也可以直接写在正则里。
//   \s*+\s* 表示"可能带空格的加号"，如 "环位：+1" 或 "环位： + 1" 都行。
//
// ============================================================



// ============================================================
// 函数：parse(rule)  — 解析特殊标记规则
// ============================================================
// 【参数说明】
//   @param {string} rule - 规则字符串
//     例如: "二选一" / "环位：+1"
//
// 【返回值说明】
//   @returns {object}
//     {
//       type: 'special',             // 固定为 'special'
//       subtype: 'choose_one'|'upcast',  // 子类型
//       success: true|false,
//       needUserSelect: false,       // 纯标记，不需要选择
//       expression: rule
//       // upcast 还有以下字段：
//       value: 1,                    // 每环增加量（仅 upcast）
//     }
//     失败时返回 { type: 'special', success: false, needUserSelect: false }
//
// ============================================================
export function parse(rule) {
    rule = String(rule).trim();

    // ----------------------------------------------------------
    // choose — 标记特性互斥关系（原"二选一"）
    // 当两个特性都有此标记时，用户只能选择其中一个
    // 通常用于子职业或分支能力的选择
    // ----------------------------------------------------------
    if (rule === 'choose' || rule === '二选一') {
        return {
            type: 'special',
            subtype: 'choose_one',       // 标记为二选一
            success: true,
            needUserSelect: false,
            expression: rule
        };
    }

    // ----------------------------------------------------------
    // 环位：+[N] — 法术升环效果
    // 标记法术每升一环，某项数值增加 N
    // 常用于描述"每升一环增加N个骰子"的效果
    // 示例：环位：+1 → 每升一环增加1d8伤害
    // ----------------------------------------------------------
    var levelMatch = rule.match(/^环位：\s*\+\s*(\d+)\s*$/);
    if (levelMatch) {
        return {
            type: 'special',
            subtype: 'upcast',                           // 标记为升环效果
            success: true,
            needUserSelect: false,
            value: parseInt(levelMatch[1], 10),          // 每环增加量
            expression: rule
        };
    }

    // 未匹配到任何特殊标记
    return {
        type: 'special',
        success: false,
        needUserSelect: false
    };
};